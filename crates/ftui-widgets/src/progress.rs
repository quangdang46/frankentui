impl ftui_a11y::Accessible for ProgressBar<'_> {
    fn accessibility_nodes(&self, area: Rect) -> Vec<ftui_a11y::node::A11yNodeInfo> {
        use ftui_a11y::node::{A11yNodeInfo, A11yRole, A11yState};

        let id = crate::a11y_node_id(area);
        let display_text = self.effective_label().unwrap_or_else(|| {
            if self.mode == ProgressBarMode::Indeterminate {
                "...".to_owned()
            } else {
                let pct = (self.ratio * 100.0).round() as u32;
                format!("{pct}%")
            }
        });

        let state = if self.mode == ProgressBarMode::Indeterminate {
            A11yState {
                busy: true,
                value_text: Some(display_text.clone()),
                ..A11yState::default()
            }
        } else {
            A11yState {
                value_now: Some(self.ratio),
                value_min: Some(0.0),
                value_max: Some(1.0),
                value_text: Some(display_text.clone()),
                ..A11yState::default()
            }
        };

        vec![
            A11yNodeInfo::new(id, A11yRole::ProgressBar, area)
                .with_name(display_text)
                .with_state(state),
        ]
    }
}

