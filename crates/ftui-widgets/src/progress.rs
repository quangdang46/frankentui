/// A single item within a [`ProgressBarGroup`].
#[derive(Debug, Clone)]
pub struct ProgressBarGroupItem<'a> {
    /// Human-readable label displayed above or beside the bar.
    pub label: &'a str,
    /// Short status text shown on the right side of the label line.
    pub status: Option<&'a str>,
    /// The progress bar configuration.
    pub bar: ProgressBar<'a>,
}

impl<'a> ProgressBarGroupItem<'a> {
    /// Create a new group item with a label and a progress bar.
    pub fn new(label: &'a str, bar: ProgressBar<'a>) -> Self {
        Self {
            label,
            status: None,
            bar,
        }
    }

    /// Set the status text.
    #[must_use]
    pub fn status(mut self, status: &'a str) -> Self {
        self.status = Some(status);
        self
    }
}

/// A panel that renders multiple [`ProgressBarGroupItem`]s stacked vertically.
///
/// Each item renders as:
///
/// ```text
/// Label text                                         [Status]
/// [======================== bar ========================]
/// ```
#[derive(Debug, Clone)]
pub struct ProgressBarGroup<'a> {
    items: Vec<ProgressBarGroupItem<'a>>,
    style: Style,
    spacing: u16,
    block: Option<Block<'a>>,
}

impl<'a> ProgressBarGroup<'a> {
    /// Create an empty group.
    pub fn new() -> Self {
        Self {
            items: Vec::new(),
            style: Style::default(),
            spacing: 0,
            block: None,
        }
    }

    /// Add an item to the group.
    #[must_use]
    pub fn add(mut self, item: ProgressBarGroupItem<'a>) -> Self {
        self.items.push(item);
        self
    }

    /// Set the base style.
    #[must_use]
    pub fn style(mut self, style: Style) -> Self {
        self.style = style;
        self
    }

    /// Set vertical spacing (in rows) between items.
    #[must_use]
    pub fn spacing(mut self, spacing: u16) -> Self {
        self.spacing = spacing;
        self
    }

    /// Wrap the group in a [`Block`] container.
    #[must_use]
    pub fn block(mut self, block: Block<'a>) -> Self {
        self.block = Some(block);
        self
    }
}

impl Default for ProgressBarGroup<'_> {
    fn default() -> Self {
        Self::new()
    }
}

impl<'a> Widget for ProgressBarGroup<'a> {
    fn render(&self, area: Rect, frame: &mut Frame) {
        #[cfg(feature = "tracing")]
        let _span = tracing::debug_span!(
            "widget_render",
            widget = "ProgressBarGroup",
            x = area.x,
            y = area.y,
            w = area.width,
            h = area.height
        )
        .entered();

        let deg = frame.buffer.degradation;
        if !deg.render_content() {
            return;
        }

        let base_style = if deg.apply_styling() {
            self.style
        } else {
            Style::default()
        };

        let inner_area = match &self.block {
            Some(b) => {
                b.render(area, frame);
                b.inner(area)
            }
            None => area,
        };

        if inner_area.is_empty() || self.items.is_empty() {
            return;
        }

        // Each item uses 2 rows: one for label+status, one for the bar
        // Plus spacing between items (but not after the last)
        let rows_per_item = 2u16.saturating_add(self.spacing);
        let total_rows = self
            .items
            .len()
            .saturating_mul(rows_per_item as usize)
            .saturating_sub(self.spacing as usize); // no spacing after last
        if total_rows == 0 {
            return;
        }

        let mut y = inner_area.y;
        let max_y = inner_area.bottom();

        for (i, item) in self.items.iter().enumerate() {
            if y >= max_y {
                break;
            }

            let bar_row = y;

            let label_width = display_width(item.label);
            let status_width = item.status.map_or(0, display_width);

            let bar_area = Rect::new(inner_area.x, bar_row, inner_area.width, 1);

            // Draw the label text at the left
            if label_width > 0 && deg.render_decorative() {
                crate::draw_text_span(
                    frame,
                    bar_area.x,
                    bar_row,
                    item.label,
                    base_style,
                    bar_area.right(),
                );
            }

            // Draw the progress bar
            item.bar.render(bar_area, frame);

            // Draw status text at the right
            if let Some(status) = item.status {
                if deg.render_decorative() {
                    let status_x = bar_area.right().saturating_sub(status_width as u16);
                    if status_x > bar_area.x.saturating_add(label_width as u16) {
                        crate::draw_text_span(
                            frame,
                            status_x,
                            bar_row,
                            status,
                            base_style,
                            bar_area.right(),
                        );
                    }
                }
            }

            y = y.saturating_add(1); // bar row

            // Spacing between items (not after the last)
            if i + 1 < self.items.len() {
                y = y.saturating_add(self.spacing);
            }
        }
    }
}

impl MeasurableWidget for ProgressBarGroup<'_> {
    fn measure(&self, _available: Size) -> SizeConstraints {
        let rows_per_item = 2u16.saturating_add(self.spacing);
        let total_rows = self
            .items
            .len()
            .saturating_mul(rows_per_item as usize)
            .saturating_sub(self.spacing as usize);

        let (block_width, block_height) = self
            .block
            .as_ref()
            .map(|b| {
                let inner = b.inner(Rect::new(0, 0, 100, 100));
                let w_overhead = 100u16.saturating_sub(inner.width);
                let h_overhead = 100u16.saturating_sub(inner.height);
                (w_overhead, h_overhead)
            })
            .unwrap_or((0, 0));

        let min_width = 1u16.saturating_add(block_width);
        let min_height = (total_rows as u16).saturating_add(block_height);

        SizeConstraints {
            min: Size::new(min_width, min_height),
            preferred: Size::new(min_width, min_height),
            max: None,
        }
    }

    fn has_intrinsic_size(&self) -> bool {
        true
    }
}

