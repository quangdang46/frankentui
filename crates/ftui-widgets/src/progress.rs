#![forbid(unsafe_code)]

//! Progress bar widget.

use crate::block::Block;
use crate::{
    MeasurableWidget, SizeConstraints, Widget, apply_style, clear_text_area, clear_text_row,
};
use ftui_core::geometry::{Rect, Size};
use ftui_render::cell::{Cell, PackedRgba};
use ftui_render::frame::{Frame, HitId, HitRegion};
use ftui_style::Style;
use ftui_text::display_width;

/// Hit region tag for the pause button on a progress bar.
pub const PROGRESS_HIT_PAUSE: HitRegion = HitRegion::Custom(11);
/// Hit region tag for the cancel button on a progress bar.
pub const PROGRESS_HIT_CANCEL: HitRegion = HitRegion::Custom(12);

/// Whether the progress bar is determinate (known progress) or indeterminate (marquee).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ProgressBarMode {
    /// Known progress ratio (0.0 ..= 1.0).  The bar shows a filled portion.
    Determinate,
    /// Unknown duration — the bar shows a sliding marquee segment.
    Indeterminate,
}

impl Default for ProgressBarMode {
    fn default() -> Self {
        Self::Determinate
    }
}

/// A widget to display a progress bar.
///
/// # Modes
///
/// - **Determinate**: use [`ProgressBar::determinate`] with `current / total` to show exact
///   progress.  The bar fills proportionally and an optional auto-label can show the percentage.
/// - **Indeterminate**: use [`ProgressBar::indeterminate`] to show a sliding marquee segment
///   for operations with unknown duration.  The caller advances [`marquee_offset`] each tick.
///
/// # Pause / Cancel
///
/// When a [`HitId`] is assigned and [`show_pause`] / [`show_cancel`] is set, the bar renders
/// small clickable targets at the right edge and registers hit regions tagged with
/// [`PROGRESS_HIT_PAUSE`] / [`PROGRESS_HIT_CANCEL`].
///
/// # Accessibility
///
/// Set [`reduced_motion(true)`] to replace the marquee animation with a static centered
/// segment, respecting the user's motion preferences.
///
/// [`marquee_offset`]: Self::marquee_offset
/// [`show_pause`]: Self::show_pause
/// [`show_cancel`]: Self::show_cancel
/// [`reduced_motion(true)`]: Self::reduced_motion
#[derive(Debug, Clone)]
pub struct ProgressBar<'a> {
    block: Option<Block<'a>>,
    ratio: f64,
    mode: ProgressBarMode,
    current: Option<u64>,
    total: Option<u64>,
    label: Option<&'a str>,
    auto_label: bool,
    marquee_offset: u16,
    marquee_segment_width: Option<u16>,
    style: Style,
    gauge_style: Style,
    hit_id: Option<HitId>,
    show_pause: bool,
    show_cancel: bool,
    reduced_motion: bool,
}

impl Default for ProgressBar<'_> {
    fn default() -> Self {
        Self {
            block: None,
            ratio: 0.0,
            mode: ProgressBarMode::Determinate,
            current: None,
            total: None,
            label: None,
            auto_label: false,
            marquee_offset: 0,
            marquee_segment_width: None,
            style: Style::default(),
            gauge_style: Style::default(),
            hit_id: None,
            show_pause: false,
            show_cancel: false,
            reduced_motion: false,
        }
    }
}

impl<'a> ProgressBar<'a> {
    /// Create a new progress bar with default settings.
    #[must_use]
    pub fn new() -> Self {
        Self::default()
    }

    /// Set the surrounding block.
    #[must_use]
    pub fn block(mut self, block: Block<'a>) -> Self {
        self.block = Some(block);
        self
    }

    /// Set the progress ratio (clamped to 0.0..=1.0).
    ///
    /// Note: this is overridden by [`determinate`] which computes the ratio from
    /// `current / total`.
    ///
    /// [`determinate`]: Self::determinate
    #[must_use]
    pub fn ratio(mut self, ratio: f64) -> Self {
        self.ratio = if ratio.is_nan() {
            0.0
        } else {
            ratio.clamp(0.0, 1.0)
        };
        self
    }

    /// Set the centered label text.
    ///
    /// If a label is set here it takes priority over the auto-label generated by
    /// [`auto_label`].
    ///
    /// [`auto_label`]: Self::auto_label
    #[must_use]
    pub fn label(mut self, label: &'a str) -> Self {
        self.label = Some(label);
        self
    }

    /// Set the base style.
    #[must_use]
    pub fn style(mut self, style: Style) -> Self {
        self.style = style;
        self
    }

    /// Set the filled portion style.
    #[must_use]
    pub fn gauge_style(mut self, style: Style) -> Self {
        self.gauge_style = style;
        self
    }

    // ------------------------------------------------------------------
    // New builder methods
    // ------------------------------------------------------------------

    /// Switch to **determinate** mode with a known `current` / `total`.
    ///
    /// The ratio is computed as `current / total` (clamped to `0.0 ..= 1.0`).
    /// Auto-label is enabled so that a percentage text is shown when no
    /// explicit [`label`] is set.
    ///
    /// # Panics
    ///
    /// Panics if `total == 0`.
    ///
    /// [`label`]: Self::label
    #[must_use]
    pub fn determinate(mut self, current: u64, total: u64) -> Self {
        assert!(total > 0, "ProgressBar::determinate: total must be > 0");
        self.current = Some(current);
        self.total = Some(total);
        self.ratio = (current as f64 / total as f64).clamp(0.0, 1.0);
        self.mode = ProgressBarMode::Determinate;
        self.auto_label = true;
        self
    }

    /// Switch to **indeterminate** mode (marquee animation).
    ///
    /// The bar shows a sliding segment whose position is controlled by
    /// [`marquee_offset`].  Advance `marquee_offset` by 1 (or more) each
    /// frame to animate.
    ///
    /// [`marquee_offset`]: Self::marquee_offset
    #[must_use]
    pub fn indeterminate(mut self) -> Self {
        self.mode = ProgressBarMode::Indeterminate;
        self
    }

    /// Set the marquee animation offset (in cells).
    ///
    /// Only meaningful in indeterminate mode.  The offset wraps at the bar's
    /// rendered width.
    #[must_use]
    pub fn marquee_offset(mut self, offset: u16) -> Self {
        self.marquee_offset = offset;
        self
    }

    /// Override the marquee segment width (in cells).
    ///
    /// When unset the segment defaults to `max(1, width / 3)`.
    #[must_use]
    pub fn marquee_segment_width(mut self, width: u16) -> Self {
        self.marquee_segment_width = Some(width);
        self
    }

    /// Enable or disable the auto-generated label.
    ///
    /// When enabled (and no explicit [`label`] is set), the bar renders a
    /// percentage string such as `"60%"` (determinate) or `"..."` (indeterminate).
    ///
    /// [`label`]: Self::label
    #[must_use]
    pub fn auto_label(mut self, enable: bool) -> Self {
        self.auto_label = enable;
        self
    }

    /// Assign a hit-testing ID for interactive regions.
    ///
    /// When set, pause and cancel buttons can register hit regions for mouse
    /// interaction.
    #[must_use]
    pub fn hit_id(mut self, id: HitId) -> Self {
        self.hit_id = Some(id);
        self
    }

    /// Show a pause button (hit region [`PROGRESS_HIT_PAUSE`]) at the right edge
    /// of the bar.
    ///
    /// Requires a [`hit_id`] to be set.
    ///
    /// [`hit_id`]: Self::hit_id
    #[must_use]
    pub fn show_pause(mut self, show: bool) -> Self {
        self.show_pause = show;
        self
    }

    /// Show a cancel button (hit region [`PROGRESS_HIT_CANCEL`]) at the right edge
    /// of the bar.
    ///
    /// Requires a [`hit_id`] to be set.
    ///
    /// [`hit_id`]: Self::hit_id
    #[must_use]
    pub fn show_cancel(mut self, show: bool) -> Self {
        self.show_cancel = show;
        self
    }

    /// Enable or disable reduced-motion mode.
    ///
    /// When enabled, the indeterminate marquee collapses to a static centred
    /// segment instead of animating.
    #[must_use]
    pub fn reduced_motion(mut self, enable: bool) -> Self {
        self.reduced_motion = enable;
        self
    }

    // ------------------------------------------------------------------
    // Internal helpers
    // ------------------------------------------------------------------

    /// Generate the auto-label text when `auto_label` is true and no explicit
    /// label was provided.
    fn auto_label_text(&self) -> Option<String> {
        if !self.auto_label {
            return None;
        }
        match self.mode {
            ProgressBarMode::Determinate => {
                match (self.current, self.total) {
                    (Some(c), Some(t)) => {
                        let pct = (self.ratio * 100.0).round() as u8;
                        Some(format!("{c}/{t} ({pct}%)"))
                    }
                    _ => {
                        let pct = (self.ratio * 100.0).round() as u8;
                        Some(format!("{pct}%"))
                    }
                }
            }
            ProgressBarMode::Indeterminate => Some("...".to_owned()),
        }
    }

    /// Return the text to display (explicit label, or auto-label, or None).
    fn effective_label(&self) -> Option<String> {
        self.label
            .map(|s| s.to_owned())
            .or_else(|| self.auto_label_text())
    }

    /// Draw the filled / gauge portion for determinate mode.
    fn draw_bar_filled(&self, bar_area: Rect, frame: &mut Frame, filled_width: u16) {
        let deg = frame.buffer.degradation;
        let gauge_style = if deg.apply_styling() {
            self.gauge_style
        } else {
            Style::default()
        };
        let fill_char = if deg.apply_styling() { ' ' } else { '#' };

        for y in bar_area.top()..bar_area.bottom() {
            for x in 0..filled_width {
                let cell_x = bar_area.left().saturating_add(x);
                if cell_x < bar_area.right() {
                    let mut cell = Cell::from_char(fill_char);
                    apply_style(&mut cell, gauge_style);
                    frame.buffer.set_fast(cell_x, y, cell);
                }
            }
        }
    }

    /// Draw the marquee segment for indeterminate mode.
    fn draw_marquee(&self, bar_area: Rect, frame: &mut Frame) {
        let total_width = bar_area.width;
        if total_width == 0 {
            return;
        }

        let deg = frame.buffer.degradation;
        let gauge_style = if deg.apply_styling() {
            self.gauge_style
        } else {
            Style::default()
        };
        let fill_char = if deg.apply_styling() { ' ' } else { '#' };

        let seg_width = self
            .marquee_segment_width
            .unwrap_or_else(|| (total_width / 3).max(1))
            .min(total_width);

        let base_offset = if self.reduced_motion {
            // Static centred segment
            (total_width - seg_width) / 2
        } else {
            self.marquee_offset % total_width
        };

        for y in bar_area.top()..bar_area.bottom() {
            for i in 0..seg_width {
                let cell_x = bar_area.left().saturating_add((base_offset + i) % total_width);
                if cell_x < bar_area.right() {
                    let mut cell = Cell::from_char(fill_char);
                    apply_style(&mut cell, gauge_style);
                    frame.buffer.set_fast(cell_x, y, cell);
                }
            }
        }
    }

    /// Render pause / cancel hit regions and their visual indicators.
    fn render_hit_regions(&self, area: Rect, frame: &mut Frame) {
        let Some(hit_id) = self.hit_id else {
            return;
        };

        let has_buttons = self.show_pause || self.show_cancel;
        if !has_buttons {
            return;
        }

        let mut btn_x = area.right();
        let deg = frame.buffer.degradation;
        let btn_style = if deg.apply_styling() {
            self.style
        } else {
            Style::default()
        };

        if self.show_cancel {
            btn_x = btn_x.saturating_sub(1);
            if btn_x >= area.left() {
                let mut cell = Cell::from_char('X');
                apply_style(&mut cell, btn_style);
                frame.buffer.set_fast(btn_x, area.y, cell);
                frame.register_hit(
                    Rect::new(btn_x, area.y, 1, area.height),
                    hit_id,
                    PROGRESS_HIT_CANCEL,
                    1,
                );
            }
        }

        if self.show_pause {
            let avail = btn_x.saturating_sub(area.left());
            if avail >= 2 {
                btn_x = btn_x.saturating_sub(2);
                crate::draw_text_span(frame, btn_x, area.y, "||", btn_style, area.right());
                frame.register_hit(
                    Rect::new(btn_x, area.y, 2.min(avail), area.height),
                    hit_id,
                    PROGRESS_HIT_PAUSE,
                    0,
                );
            } else if avail == 1 {
                btn_x = btn_x.saturating_sub(1);
                let mut cell = Cell::from_char('|');
                apply_style(&mut cell, btn_style);
                frame.buffer.set_fast(btn_x, area.y, cell);
                frame.register_hit(
                    Rect::new(btn_x, area.y, 1, area.height),
                    hit_id,
                    PROGRESS_HIT_PAUSE,
                    0,
                );
            }
        }
    }
}

impl<'a> Widget for ProgressBar<'a> {
    fn render(&self, area: Rect, frame: &mut Frame) {
        #[cfg(feature = "tracing")]
        let _span = tracing::debug_span!(
            "widget_render",
            widget = "ProgressBar",
            x = area.x,
            y = area.y,
            w = area.width,
            h = area.height
        )
        .entered();

        let deg = frame.buffer.degradation;

        // Skeleton+: skip entirely
        if !deg.render_content() {
            return;
        }

        // EssentialOnly: just show percentage / status text, no bar
        if !deg.render_decorative() {
            clear_text_area(frame, area, Style::default());
            let display_text = self.effective_label().unwrap_or_else(|| {
                let pct = format!("{}%", (self.ratio * 100.0) as u8);
                pct
            });
            crate::draw_text_span(
                frame,
                area.x,
                area.y,
                &display_text,
                Style::default(),
                area.right(),
            );
            return;
        }

        let base_style = if deg.apply_styling() {
            self.style
        } else {
            Style::default()
        };

        clear_text_area(frame, area, base_style);

        let bar_area = match &self.block {
            Some(b) => {
                b.render(area, frame);
                b.inner(area)
            }
            None => area,
        };

        if bar_area.is_empty() {
            return;
        }

        // Reserve space at the right for pause/cancel buttons if applicable.
        let mut button_reserve: u16 = 0;
        if self.hit_id.is_some() && (self.show_pause || self.show_cancel) {
            if self.show_cancel {
                button_reserve = button_reserve.saturating_add(1);
            }
            if self.show_pause {
                button_reserve = button_reserve.saturating_add(2);
            }
        }

        let bar_content_width = if button_reserve >= bar_area.width {
            0
        } else {
            bar_area.width.saturating_sub(button_reserve)
        };

        let content_area = Rect::new(bar_area.x, bar_area.y, bar_content_width, bar_area.height);

        if content_area.width > 0 {
            match self.mode {
                ProgressBarMode::Determinate => {
                    let max_width = content_area.width as f64;
                    let filled_width = if self.ratio >= 1.0 {
                        content_area.width
                    } else {
                        (max_width * self.ratio).floor() as u16
                    };
                    self.draw_bar_filled(content_area, frame, filled_width);
                }
                ProgressBarMode::Indeterminate => {
                    self.draw_marquee(content_area, frame);
                }
            }
        }

        // Draw label (centered within the overall bar area)
        let label_style = if deg.apply_styling() {
            self.style
        } else {
            Style::default()
        };
        if let Some(label) = self.effective_label() {
            let label_width = display_width(&label);
            let label_x = bar_area
                .left()
                .saturating_add(((bar_area.width as usize).saturating_sub(label_width) / 2) as u16);
            let label_y = bar_area.top().saturating_add(bar_area.height / 2);

            crate::draw_text_span(
                frame,
                label_x,
                label_y,
                &label,
                label_style,
                bar_area.right(),
            );
        }

        // Render pause/cancel buttons and hit regions
        if self.hit_id.is_some() && (self.show_pause || self.show_cancel) {
            self.render_hit_regions(bar_area, frame);
        }
    }
}

impl MeasurableWidget for ProgressBar<'_> {
    fn measure(&self, _available: Size) -> SizeConstraints {
        // ProgressBar fills available width, has fixed height of 1 (or block inner height)
        let (block_width, block_height) = self
            .block
            .as_ref()
            .map(|b| {
                let inner = b.inner(Rect::new(0, 0, 100, 100));
                let w_overhead = 100u16.saturating_sub(inner.width);
                let h_overhead = 100u16.saturating_sub(inner.height);
                (w_overhead, h_overhead)
            })
            .unwrap_or((0, 0));

        // Minimum: 1 cell for bar + block overhead
        let min_width = 1u16.saturating_add(block_width);
        let min_height = 1u16.saturating_add(block_height);

        SizeConstraints {
            min: Size::new(min_width, min_height),
            preferred: Size::new(min_width, min_height), // Fills width, so preferred = min
            max: None, // Can grow to fill available space
        }
    }

    fn has_intrinsic_size(&self) -> bool {
        true
    }
}

